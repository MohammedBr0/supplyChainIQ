import frappe
from frappe import _
from frappe.model.document import Document

from supplychain_iq import tenancy

ROLE = "IQ Integration"


class IQIntegrationConnection(Document):
	def validate(self):
		before = self.get_doc_before_save()
		for f in ("integration_user", "api_key", "last_used_on"):  # server-managed
			if not self.flags.iq_server_change:
				self.set(f, before.get(f) if before else None)

	def on_update(self):
		if self.integration_user and frappe.db.exists("User", self.integration_user):
			if frappe.db.get_value("User", self.integration_user, "enabled") != (1 if self.enabled else 0):
				frappe.db.set_value("User", self.integration_user, "enabled", 1 if self.enabled else 0)
		tenancy.clear_cache()

	def on_trash(self):
		if self.integration_user and frappe.db.exists("User", self.integration_user):
			frappe.db.set_value("User", self.integration_user, "enabled", 0)

	@frappe.whitelist()
	def generate_credentials(self):
		"""Create (or rotate) the API user's key and secret. The secret is returned once and never stored in clear."""
		self.check_permission("write")
		if not ({"IQ Org Admin", "System Manager"} & set(frappe.get_roles())):
			frappe.throw(_("Only an Org Admin can generate integration credentials."), frappe.PermissionError)
		if not self.integration_user:
			email = f"api-{frappe.scrub(self.name)}-{frappe.generate_hash(length=6)}@integrations.example"
			user = frappe.get_doc({
				"doctype": "User", "email": email, "first_name": f"API {self.connection_name}"[:60],
				"send_welcome_email": 0, "user_type": "Website User", "roles": [{"role": ROLE}],
			})
			user.flags.ignore_permissions = True
			user.insert()
			self.integration_user = user.name
		user = frappe.get_doc("User", self.integration_user)
		secret = frappe.generate_hash(length=24)
		user.api_key = frappe.generate_hash(length=15)
		user.api_secret = secret
		user.enabled = 1 if self.enabled else 0
		user.flags.ignore_permissions = True
		user.save()
		self.api_key = user.api_key
		self.flags.iq_server_change = True
		self.save()
		self.add_comment("Info", _("API credentials generated by {0}.").format(frappe.session.user))
		return {"api_key": user.api_key, "api_secret": secret}
